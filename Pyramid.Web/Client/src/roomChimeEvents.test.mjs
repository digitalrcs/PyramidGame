import assert from 'node:assert/strict';
import {roomObservation,roomEvents,roomSound} from './roomChimeEvents.js';

let checks=0;
const state={packId:'oasis',level:1,roomId:'entry',roomLit:true,roomActivity:true,score:10,solved:0,moves:3,started:'2026-10-01',won:false,items:['rope'],roomChanges:{visible:true,openRoutes:['west'],solved:[]}};
const member=(id,here=true)=>({id,name:id,here,online:true});
const observe=(changes={},members=[member('self')],active=true,partyId='one')=>roomObservation({...state,...changes},{id:partyId,members},'self',active);
const expect=(name,previous,next,kinds,text)=>{const events=roomEvents(previous,next);assert.deepEqual(events.map(e=>e.kind),kinds,name);if(text)assert.match(events.map(e=>e.text).join(' '),text,name);checks++;};
const initial=observe();
expect('first active room retains investigation cue',null,initial,['activity']);
expect('initial companions do not announce arrivals',null,observe({},[member('self'),member('friend')]),['activity']);
expect('unchanged polls are silent',initial,observe(),[]);
expect('newly lit room',observe({roomLit:false,items:[],roomChanges:{visible:false,openRoutes:[],solved:[]}}),initial,['activity'],/now visible/);
expect('new route',initial,observe({roomChanges:{visible:true,openRoutes:['west','east'],solved:[]}}),['activity'],/route/);
expect('solved local puzzle',initial,observe({roomChanges:{visible:true,openRoutes:['west'],solved:['bell']}}),['puzzle'],/puzzle/);
expect('appeared item',initial,observe({items:['rope','key']}),['activity'],/item/);
expect('removed item silent',initial,observe({items:[]}),[]);
expect('reordered sets silent',observe({items:['rope','key']}),observe({items:['key','rope']}),[]);
expect('self is never arrival',observe({},[]),initial,[]);
expect('companion arriving from elsewhere',observe({},[member('self'),member('friend',false)]),observe({},[member('self'),member('friend')]),['arrival'],/friend has entered/);
expect('initial room entry ignores occupants',initial,observe({roomId:'vault'},[member('self'),member('friend')]),['activity']);
expect('departure silent',observe({},[member('self'),member('friend')]),initial,[]);
expect('wake-up is not entry',observe({},[{...member('friend'),online:false}]),observe({},[member('friend')]),[]);
expect('switch expedition silent',initial,observe({},[member('friend')],true,'two'),[]);
expect('switch campaign silent',initial,observe({packId:'other'}),[]);
expect('inactive editor suppresses sound',initial,observe({items:['rope','key']},[member('friend')],false),[]);
expect('resuming baselines occupants', {...initial,active:false},observe({},[member('friend')]),['activity']);
expect('return from library to different world silent',{...initial,active:false},observe({},[member('friend')],true,'two'),[]);
expect('optional NPC arrival',initial,observe({characters:[{id:'guardian',name:'The guardian'}]}),['arrival'],/guardian/);
expect('unchanged NPC silent',observe({characters:['guardian']}),observe({characters:['guardian']}),[]);
expect('dark room does not reveal NPC',observe({roomLit:false,roomChanges:{visible:false}}),observe({roomLit:false,roomChanges:{visible:false},characters:['guardian']}),[]);
expect('dark data cannot announce item or puzzle',observe({roomLit:false,roomChanges:{visible:false}}),observe({roomLit:false,items:['secret'],roomChanges:{visible:false,solved:['secret'],openRoutes:['east']}}),[]);
expect('combined changes have distinct activity and arrival events',initial,observe({items:['rope','key']},[member('friend')]),['activity','arrival']);
expect('no state silent',initial,null,[]);
expect('point gain',initial,observe({score:12}),['reward'],/2 points/);
expect('singular point gain',initial,observe({score:11}),['reward'],/1 point\./);
expect('point loss silent',initial,observe({score:5}),[]);
expect('moving discovery bonus',initial,observe({roomId:'vault',score:13,moves:4}),['reward','activity']);
expect('puzzle completion',initial,observe({solved:1}),['puzzle']);
expect('win completion',initial,observe({won:true}),['victory']);
expect('first hydration high score is not reward',null,observe({score:1000,solved:30,won:true}),['activity']);
expect('switch save high score is not reward',initial,observe({score:1000,solved:30},[],true,'other'),[]);
expect('resuming changed totals is not reward',{...initial,active:false},observe({score:1000,solved:30}),['activity']);
expect('new reset timestamp suppresses rewards',initial,observe({started:'2026-10-02',score:100}),[]);
expect('reset moves suppresses rewards',initial,observe({moves:0,score:100}),[]);
expect('reset puzzle count suppresses rewards',observe({solved:5}),observe({score:100}),[]);
expect('reset victory suppresses rewards',observe({won:true}),observe({score:100}),[]);
const combined=roomEvents(initial,observe({score:40,solved:1,roomChanges:{visible:true,openRoutes:['west','east'],solved:['bell']}},[member('friend')]));
assert.equal(roomSound(combined),'puzzle','puzzle motif wins over reward, arrival and discovery');checks++;
assert.equal(combined.filter(e=>e.kind==='puzzle').length,1,'local plus total puzzle change is announced once');checks++;
assert.equal(roomSound([{kind:'reward'},{kind:'activity'}]),'reward');checks++;
assert.equal(roomSound([{kind:'victory'},{kind:'puzzle'},{kind:'reward'}]),'victory');checks++;
assert.equal(roomSound([]),null);checks++;
console.log(`${checks} room chime event checks passed.`);
